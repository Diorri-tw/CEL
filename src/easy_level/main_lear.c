// =====================================================================================================
// КАК ЧИТАТЬ ЭТИ КОММЕНТАРИИ
// Это новый уровень: мы НЕ запускаем игру, а учимся её ЧИТАТЬ. Программа берёт команды из Pong.ch8
//   и переводит каждую из них в понятную запись вроде "LD V1, 0x0C". Такая работа называется "дизассемблированием".
// Зачем это нужно? Команды игры - это просто два байта, например 6A02. Человеку трудно понять, что это значит.
//   А когда мы видим "положить 2 в регистр VA", сразу понятно, что делает игра. Дальше по этой же логике будем писать эмулятор.
// =====================================================================================================


#include <stdio.h>    // printf, fopen, fread - вывод и работа с файлами, как в base_level.
#include <stdint.h>   // uint8_t, uint16_t - числа точного размера: 8 и 16 бит.
#include <windows.h>  // Нужен только для русского текста в консоли Windows, как и в base_level.


// Константы - значения, которые не меняются. Как и в base_level, они задаются через #define.
// #define - автозамена текста ДО компиляции: везде, где написано MEMORY_SIZE, компилятор увидит 4096.
#define MEMORY_SIZE 4096        // 4 КБ памяти CHIP-8.
#define START_ADRESS 0x200      // Адрес, с которого начинается игра (512). Здесь же читаем первую команду.
#define COMMANDS_TO_SHOW 30     // Сколько команд показать на экране. Не весь файл, чтобы вывод не был слишком длинным.


// Главная функция этого уровня: превращает одну команду (2 байта, число op) в понятную запись.
// Тип void - функция ничего не возвращает, она только печатает.
// uint16_t op - вся команда целиком, два байта склеенные в одно 16-битное число. Например, 0x6A02.
//
// Как устроена команда CHIP-8? Все команды имеют длину 2 байта (16 бит), и первые 4 бита говорят, КАКАЯ это команда:
//   6A02 -> первая цифра 6 = "положить число в регистр".
//   Остальные цифры - это параметры: номер регистра, число, адрес.
// Чтобы достать параметры, используем битовые операции:
void print_mnemonic(uint16_t op) {
    // >> - сдвиг битов вправо. (op >> 8) отбрасывает два младших байта и оставляет старший байт.
    // & 0x0F - маска: оставляет только последние 4 бита (одну шестнадцатеричную цифру).
    // x - номер регистра (вторая цифра команды). Например, в 6A02 это A, то есть регистр VA.
    uint8_t x = (op >> 8) & 0x0F;
    // y - номер второго регистра (третья цифра). Используется в командах, где два регистра.
    uint8_t y = (op >> 4) & 0x0F;
    // n - последняя цифра команды (четвёртая). Иногда это маленькое число, иногда подкоманда.
    uint8_t n = op & 0x0F;
    // nn - последние два байта (две последние цифры). Обычно это непосредственное число, которое кладём в регистр.
    uint8_t nn = op & 0xFF;
    // nnn - три последние цифры, то есть адрес. Например, в 2D4 это адрес 0x2D4.
    uint16_t nnn = op & 0x0FFF;

    // switch - выбор по значению. Смотрим на первую цифру команды (op >> 12 - сдвигаем на 12 бит, остаётся первая цифра).
    // Это аналог цепочки if, только аккуратнее, когда вариантов много.
    switch (op >> 12) {
        case 0x0:
            // Группа 0: особые команды. Они не имеют параметров, поэтому смотрим на всю команду целиком.
            if (op == 0x00E0) printf("CLS");                // CLS - очистить экран.
            else if (op == 0x00EE) printf("RET");          // RET - вернуться из подпрограммы (снять верхнюю "тарелку" стека).
            else printf("SYS 0x%03X", nnn);                // Остальное - старая команда, которую современные игры не используют.
            break;                                          // break - выход из switch, чтобы не выполнялись следующие case.
        case 0x1: printf("JP 0x%03X", nnn); break;           // JP - прыжок на адрес nnn (записать адрес в pc).
        case 0x2: printf("CALL 0x%03X", nnn); break;         // CALL - вызов подпрограммы по адресу (с запоминанием возврата в стек).
        case 0x3: printf("SE V%X, 0x%02X", x, nn); break;    // SE - "пропустить следующую команду, если регистр равен числу".
        case 0x4: printf("SNE V%X, 0x%02X", x, nn); break;   // SNE - то же, но если НЕ равен.
        case 0x5: printf("SE V%X, V%X", x, y); break;        // SE для двух регистров.
        case 0x6: printf("LD V%X, 0x%02X", x, nn); break;    // LD - "загрузить" число в регистр. Самая частая команда.
        case 0x7: printf("ADD V%X, 0x%02X", x, nn); break;   // ADD - прибавить число к регистру.

        case 0x8:
            // Группа 8: команды с двумя регистрами. Какая именно операция, решает последняя цифра n.
            // Поэтому здесь ещё один switch - внутри switch. Это нормально: одна вложенность для одной группы.
            switch (n) {
                case 0x0: printf("LD V%X, V%X", x, y); break;   // Скопировать значение из Vy в Vx.
                case 0x1: printf("OR V%X, V%X", x, y); break;   // Побитовое ИЛИ.
                case 0x2: printf("AND V%X, V%X", x, y); break;  // Побитовое И.
                case 0x3: printf("XOR V%X, V%X", x, y); break;  // Побитовое исключающее ИЛИ.
                case 0x4: printf("ADD V%X, V%X", x, y); break;  // Сложение. Если переполнилось, VF = 1.
                case 0x5: printf("SUB V%X, V%X", x, y); break;  // Вычитание Vy из Vx.
                case 0x6: printf("SHR V%X", x); break;          // Сдвиг вправо (деление на 2).
                case 0x7: printf("SUBN V%X, V%X", x, y); break; // Вычитание Vx из Vy (наоборот).
                case 0xE: printf("SHL V%X", x); break;          // Сдвиг влево (умножение на 2).
                default:  printf("??? 8%X%X%X", x, y, n); break; // Такой команды нет. Вывод "???", чтобы было видно ошибку.
            }
            break;

        case 0x9: printf("SNE V%X, V%X", x, y); break;       // SNE для двух регистров.
        case 0xA: printf("LD I, 0x%03X", nnn); break;        // Записать адрес в регистр I. Так игра говорит: "картинка лежит тут".
        case 0xB: printf("JP V0, 0x%03X", nnn); break;       // Прыжок по адресу, смещённому на V0.
        case 0xC: printf("RND V%X, 0x%02X", x, nn); break;   // Случайное число, объединённое с nn по "И", кладём в Vx.
        case 0xD: printf("DRW V%X, V%X, %X", x, y, n); break; // DRW - нарисовать спрайт (картинку) в позиции Vx, Vy. Высота n строк.

        case 0xE:
            // Группа E: проверка нажатия клавиш. Клавиши в CHIP-8 - это 16 кнопок (0-F).
            if (nn == 0x9E) printf("SKP V%X", x);    // SKP - пропустить следующую команду, если клавиша Vx нажата.
            else if (nn == 0xA1) printf("SKNP V%X", x); // SKNP - пропустить, если клавиша НЕ нажата.
            else printf("??? %04X", op);
            break;

        case 0xF:
            // Группа F: разные команды для таймеров, памяти и клавиатуры. Тип команды определяет nn.
            switch (nn) {
                case 0x07: printf("LD V%X, DT", x); break; // Прочитать таймер задержки DT в регистр.
                case 0x0A: printf("LD V%X, K", x); break;  // Ждать нажатия клавиши и записать её номер в регистр.
                case 0x15: printf("LD DT, V%X", x); break; // Записать значение регистра в таймер задержки.
                case 0x18: printf("LD ST, V%X", x); break; // Записать значение регистра в таймер звука (пищалка).
                case 0x1E: printf("ADD I, V%X", x); break; // Прибавить Vx к адресу I.
                case 0x29: printf("LD F, V%X", x); break;  // Адрес шрифта для цифры Vx (картинки цифр 0-F).
                case 0x33: printf("LD B, V%X", x); break;  // Записать три цифры числа Vx в память (для вывода очков).
                case 0x55: printf("LD [I], V%X", x); break; // Сохранить регистры V0..Vx в память по адресу I.
                case 0x65: printf("LD V%X, [I]", x); break; // Загрузить регистры V0..Vx из памяти по адресу I.
                default:   printf("??? %04X", op); break;
            }
            break;

        default: printf("??? %04X", op); break; // Сюда попадаем, только если первая цифра не от 0 до F. Такого быть не может, но на всякий случай.
    }
}


// main - точка входа программы, как и в base_level.
int main() {
    // Настраиваем консоль на UTF-8, как и в base_level.
    SetConsoleCP(CP_UTF8);
    SetConsoleOutputCP(CP_UTF8);

    // static - переменная живёт всё время работы программы, а не только внутри main.
    // Здесь это просто массив памяти. Он уже заполнен нулями.
    // Зачем static, если это внутри main? Большие массивы лучше держать в статической памяти, а не в стеке функции.
    //   Стек маленький, и 4096 байт там могут не влезть. Пока что это безопасно, но привычка полезная.
    static uint8_t memory[MEMORY_SIZE];

    // Открываем ROM-файл. Этот блок такой же, как в base_level/main_lear.c, поэтому подробности там.
    const char *rom_path = "roms/Pong.ch8";
    FILE *rom = fopen(rom_path, "rb");
    if (rom == NULL) {
        printf("Ошибка: Не удалось открыть файл %s\n", rom_path);
        return 1; // 1 = программа закончилась с ошибкой.
    }

    // Узнаём размер файла: ставим курсор в конец, читаем позицию, возвращаем курсор в начало.
    fseek(rom, 0, SEEK_END);
    long rom_size = ftell(rom);
    rewind(rom);

    // Проверяем, что игра влезает в память начиная с 0x200.
    if (rom_size > (MEMORY_SIZE - START_ADRESS)) {
        printf("Ошибка: ROM слишком большой для памяти Chip-8!\n");
        fclose(rom);
        return 1;
    }

    // Читаем всю игру в память, начиная с адреса 0x200. &memory[START_ADRESS] - адрес, куда класть байты.
    fread(&memory[START_ADRESS], sizeof(uint8_t), rom_size, rom);
    fclose(rom); // Файл больше не нужен, всё уже в памяти.

    printf("Дизассемблер: первые команды из %s\n\n", rom_path);

    // Сколько команд показываем. Каждая команда 2 байта, поэтому делим размер файла на 2.
    // Если игра короткая, показываем все. Если длинная - только COMMANDS_TO_SHOW.
    long commands = rom_size / 2;
    if (commands > COMMANDS_TO_SHOW) commands = COMMANDS_TO_SHOW;

    // Цикл: проходим по командам по одной. i - номер команды (0, 1, 2 ...), а не адрес.
    for (long i = 0; i < commands; i++) {
        // Адрес текущей команды. Команда i лежит по адресу 0x200 + i * 2, потому что каждая команда 2 байта.
        uint16_t address = START_ADRESS + i * 2;

        // Склеиваем два байта в одно число. Это ключевая строчка всего уровня:
        //   memory[address] - старший байт (первые две цифры команды), например 0x6A.
        //   << 8 - сдвигаем его на 8 бит влево, то есть на два места в 16-ричной записи: 0x6A -> 0x6A00.
        //   | memory[address + 1] - "или" с младшим байтом (0x02). Получаем 0x6A02.
        // Почему нельзя просто записать их рядом? Компьютер хранит числа в битах, а не текстом. Склейка делается битами.
        uint16_t op = (memory[address] << 8) | memory[address + 1];

        // Печатаем адрес, сырые байты команды (%04X - 4 16-ричных цифры) и её понятную запись.
        printf("0x%03X: %04X   ", address, op);
        print_mnemonic(op);
        printf("\n");
    }

    return 0; // Всё прошло нормально.
}
