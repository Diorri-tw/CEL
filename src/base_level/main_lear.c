// include - это предпроцессорная команда. Она берёт весь текст указанного файла и вставляет его в самое начало нашего кода.
//
// Предпроцессор - что это? Превращение main.c в main.exe идёт в несколько этапов. Самый первый этап - предпроцессор.
//   Он ещё ничего не понимает в языке C, он просто работает с текстом, как "найти и заменить" в Word:
//   видит #include - вставляет туда текст файла, видит #define - заменяет слова. И только потом за дело берётся компилятор,
//   который переводит уже готовый текст в машинный код (нули и единицы, понятные процессору).
//
// Зачем вообще что-то вставлять? Сам по себе язык C очень маленький, он даже не умеет выводить текст на экран.
//   Все полезные функции (печать, работа с файлами) написаны заранее и лежат в отдельных файлах - библиотеках.
//   Файлы с окончанием .h (h = header, "заголовок") - это как оглавление: в них написано, какие функции существуют и что они принимают.
//
// Если забыть #include, компилятор встретит, например, printf и скажет: "Я не знаю, что это такое" - и выдаст ошибку или предупреждение.
//
// Угловые скобки < > говорят компилятору: "ищи этот файл в системных папках компилятора", а не рядом с нашим main.c.
// Если бы мы писали свой собственный файл, например "cpu.h", мы бы взяли его в кавычки: #include "cpu.h" - тогда поиск начнётся с папки проекта.

#include <stdio.h> // <stdio.h> (standard input/output - стандартный ввод-вывод). Без него компьютер не поймёт, что такое printf (вывод текста) и fopen (открытие файлов).

#include <stdlib.h> // <stdlib.h> (standard library - стандартная библиотека утилит). Нужна для управления памятью и процессами.
// Прямо сейчас мы из неё ничего не используем. Но она скоро понадобится - например, функция rand() (случайное число).
// В CHIP-8 есть команда "положи в регистр случайное число", без неё не будут работать многие игры.

#include <stdint.h> // <stdint.h> (standard integer - стандартные целые числа) - добавляем специально для эмулятора.
// Она даёт типы данных с фиксированным размером: uint8_t - строго 8 бит, uint16_t - строго 16 бит.
//
// Почему не обычный int? Стандарт языка C не говорит точно, сколько места занимает int.
//   На одном компьютере это 16 бит, на другом 32. А в эмуляторе нам нужно, чтобы всё было ровно как у настоящего CHIP-8.
//
// Почему это так важно? Из-за "переполнения". В 8-битной ячейке максимум - число 255. Если к 255 прибавить 1, получится НЕ 256, а 0
//   (как на старом счётчике километров в машине: после 999999 снова идёт 000000).
//   Настоящий CHIP-8 ведёт себя именно так, и игры на это рассчитывают. Если бы ячейка была больше, получилось бы 256 и игра бы сломалась.

#include <windows.h> // <windows.h> - вставляет функции операционной системы Windows. Здесь она нужна только для настройки отображения русского языка в консоли.
// Минус: из-за неё программа соберётся только на Windows. На Linux или Mac этого файла нет. Для учёбы это не страшно.


// Так как мы пишем эмулятор CHIP-8, нам нужно подогнать всё строго под его архитектуру - та самая точность.
//
// Эмулятор - что это? CHIP-8 - это очень старая (1977 год) простенькая "игровая система".
//   Её игры - это набор команд для её процессора. Наш компьютер этих команд не понимает.
//   Эмулятор - это программа, которая притворяется тем старым компьютером: читает его команды одну за другой
//   и делает то, что каждая из них означает. По сути мы строим виртуальную приставку из кода.
//
// define - это ещё одна предпроцессорная команда (все предпроцессорные команды начинаются на #, поэтому больше повторяться не буду).
// Короче, это автозамена текста ДО того, как код начнёт компилироваться.
// К примеру, предпроцессор найдёт слово MEMORY_SIZE и заранее заменит его на 4096.
//
// Зачем, если можно просто везде написать 4096?
//   1) Понятность: слово MEMORY_SIZE само объясняет, что это. А голое 4096 через месяц никто не вспомнит, откуда оно.
//   2) Удобство: если захочешь поменять размер, исправишь в одном месте, а не будешь искать все 4096 по всему коду.
// Почему имена БОЛЬШИМИ буквами? Это не правило языка, а традиция программистов: так сразу видно, что это автозамена, а не обычная переменная.
// Обрати внимание: в конце #define НЕ ставится точка с запятой. Иначе ";" тоже вставится в код при замене и всё сломает.
//
// Про шестнадцатеричную систему (числа вида 0x200):
//   Мы считаем в десятичной системе - цифры от 0 до 9. В шестнадцатеричной цифр 16: 0-9 и ещё A=10, B=11, C=12, D=13, E=14, F=15.
//   Приставка 0x просто говорит: "дальше число в шестнадцатеричной системе". 0x200 = 2*256 + 0*16 + 0 = 512.
//   Зачем она программистам? Одна такая цифра - это ровно 4 бита, а две цифры - ровно 1 байт (от 00 до FF, то есть от 0 до 255).
//   Поэтому байты в шестнадцатеричном виде читать очень удобно, и вся документация CHIP-8 написана именно так.

#define MEMORY_SIZE 4096 // задаём размер оперативной памяти CHIP-8 (4 КБ). Это 4096 ячеек по 1 байту. Для сравнения: в твоём ПК памяти примерно в 4 миллиона раз больше.

#define START_ADRESS 0x200 // 0x200 - это число 512 в шестнадцатеричной системе. В оригинальном CHIP-8 первые 512 байт были заняты самой системой, поэтому все игры всегда загружаются начиная с 512-го байта.
// Что там лежало? На старых компьютерах в этих 512 байтах жила сама программа-интерпретатор CHIP-8 (по сути такой же эмулятор, как наш).
// Нам это место не нужно, но игры написаны с расчётом, что они начинаются с 0x200, поэтому мы соблюдаем это правило.
// Позже мы положим в эту пустую область шрифт - картинки цифр 0-F, которыми игры рисуют счёт.
// (Кстати, правильно пишется ADDRESS с двумя D. Работает и так, главное везде писать одинаково.)

#define REGISTERED_COUNT 16 // количество регистров (сверхбыстрых ячеек памяти внутри процессора) у CHIP-8.

#define STACK_SIZE 16 // максимальная глубина «стека» (памяти, которая помнит, из какого места была вызвана функция, чтобы потом вернуться назад). Подробнее про стек - ниже, в структуре.

// Теперь пишем структуру

typedef struct { // struct - это как тип данных int или float, только в int ты можешь хранить одно число, а в struct можно упаковать целый сложный объект из многих переменных.

    // Слово struct позволяет тебе создать свой собственный сложный тип данных, который объединяет внутри себя обычные переменные.
    // typedef - это слово, благодаря которому ты, грубо говоря, даёшь любому типу псевдоним, чтобы коротко его вызывать.
    // Без typedef пришлось бы каждый раз писать "struct Chip8 cpu", а с ним - просто "Chip8 cpu".
    //
    // Зачем собирать всё в одну структуру? Можно было бы сделать кучу отдельных переменных,
    //   но тогда в каждую функцию пришлось бы передавать по 8 штук. А так у нас одна "коробка" со всей приставкой внутри:
    //   передал одну коробку - и функция имеет доступ ко всему. Плюс сразу видно, из чего состоит CHIP-8.
    //   Эта структура - и есть описание "железа" приставки: её память, процессор и таймеры.
    //
    // Важно понимать: сама структура - это только ЧЕРТЁЖ. Она не занимает память, пока мы не создадим по ней настоящую переменную
    //   (мы это сделаем в main: Chip8 cpu). Как чертёж дома и сам дом.

    uint8_t memory[MEMORY_SIZE]; // 4 КБ оперативной памяти (8-битные ячейки)
    // uint8_t - тип данных: unsigned (беззнаковое, только положительное), integer (целое число), 8 бит (ровно 1 байт памяти). Может хранить числа от 0 до 255.
    // Квадратные скобки [ ] означают массив - то есть не одна ячейка, а целый ряд одинаковых ячеек подряд. Тут их 4096 штук.
    // Каждая ячейка имеет свой номер (его называют "адрес" или "индекс"). Нумерация в C начинается с НУЛЯ:
    //   первая ячейка - memory[0], последняя - memory[4095]. memory[4096] уже не существует!
    // Почему без знака (unsigned)? Байт в памяти - это просто 8 бит, отрицательных байтов не бывает. Нам нужны числа 0-255, а не -128..127.
    // Почему ячейки по 8 бит? Потому что у настоящего CHIP-8 память состоит именно из байтов. Мы копируем оригинал.

    uint8_t V[REGISTERED_COUNT]; // 16 регистров общего назначения (V0 - VF)
    // Массив из 16 регистров по 1 байту каждый. Это переменные самого процессора (в документации CHIP-8 они называются от V0 до VF), в которых он считает данные.
    // Зачем регистры, если есть память? Процессор не умеет считать прямо в памяти. Он как повар: сначала достаёт продукты
    //   из холодильника (памяти) на стол (в регистры), там их режет и смешивает (складывает, сравнивает), а потом убирает обратно.
    //   Регистров мало, зато работать с ними быстро.
    // V0..VF - это шестнадцатеричные номера: V0, V1 ... V9, VA, VB ... VF. Всего 16 штук, в коде это V[0] ... V[15].
    // Особенность: последний регистр VF (V[15]) - особенный. Процессор сам пишет в него "флажок":
    //   например, было ли переполнение при сложении или столкнулись ли две картинки на экране. Поэтому игры его для своих дел не используют.

    uint16_t I; // Индексный регистр (16-битный, для адресов)
    // uint16_t - беззнаковое целое число размером 16 бит (2 байта). Может хранить числа от 0 до 65535.
    // I - специальный индексный регистр. Он нужен для хранения адресов памяти. Так как адреса в памяти могут быть больше 255 (вплоть до 4095), обычный 8-битный регистр тут не подойдёт, поэтому он 16-битный.
    // Для чего нужен адрес? Например, игра хочет нарисовать мячик. Картинка мячика лежит где-то в памяти.
    //   Игра сначала кладёт в I адрес этой картинки ("мячик лежит вот тут"), а потом даёт команду "нарисуй то, что лежит по адресу I".
    // Почему не 12 бит, раз адреса до 4095? Типа "12 бит" в C просто нет, ближайший подходящий - 16 бит. Лишние биты просто не используются.

    uint16_t pc; // Program Counter (указатель на текущую команду)
    // pc - Program Counter (Счётчик команд). Он хранит адрес в памяти, где сейчас находится процессор, то есть какую команду игры он должен прочитать следующей. Тоже 16-битный.
    // Это как закладка в книге: процессор читает команду по адресу pc, выполняет её и сдвигает закладку дальше.
    // Каждая команда CHIP-8 занимает 2 байта, поэтому обычно pc увеличивается на 2.
    // Если игре нужно прыгнуть в другое место (например, начать уровень заново), есть команда "прыжок" - она просто записывает в pc новый адрес.



    uint16_t stack[STACK_SIZE]; // stack[16] - массив для хранения адресов возврата (стек).
    // Что такое стек? Представь стопку тарелок: кладёшь тарелку только сверху и берёшь тоже только сверху. Последнюю положил - первую взял.
    // Зачем он процессору? В игре есть "подпрограммы" - куски кода, которые вызываются из разных мест (например, "нарисовать счёт").
    //   Когда игра прыгает в подпрограмму, процессор должен запомнить, откуда он прыгнул, чтобы потом вернуться обратно.
    //   Этот адрес возврата он кладёт "тарелкой" на верх стека. Закончил подпрограмму - снял верхнюю тарелку и вернулся туда.
    //   Если внутри подпрограммы вызвали ещё одну - сверху ляжет ещё одна тарелка. Поэтому возвращаемся всегда в правильном порядке.
    // Почему uint16_t? Потому что в стеке лежат адреса, а адресам нужно больше 8 бит (как и I, и pc).
    // Если вложить подпрограммы глубже 16 раз, места не хватит - это "переполнение стека". Нормальные игры так не делают.

    uint8_t sp; // sp - Stack Pointer (Указатель стека). 8-битное число, которое работает как номер ячейки в массиве stack. Показывает, на какой «ступеньке» стека мы сейчас стоим.
    // Проще говоря, sp - это "сколько тарелок сейчас в стопке". Положили адрес - sp увеличился на 1, сняли - уменьшился на 1.
    // Хватает 8 бит, потому что значений всего 0..16.

    // Два таймера CHIP-8. Они автоматически уменьшаются на 1 каждые 1/60 секунды (60 раз в секунду), пока не дойдут до нуля.
    // delay_timer нужен для задержек в играх, а пока sound_timer больше нуля, консоль должна издавать писк.
    // Как игра делает задержку? Кладёт, например, 60 в delay_timer и ждёт, пока там станет 0. 60 тиков по 1/60 секунды = ровно 1 секунда.
    //   Так скорость игры не зависит от того, насколько быстрый процессор.
    // Как игра пищит? Кладёт число в sound_timer - и пока он не дошёл до нуля, звучит писк. Положила 30 - пищит полсекунды.
    // Почему 8 бит? Максимум 255 тиков, то есть чуть больше 4 секунд, - для старых игр этого достаточно.
    uint8_t delay_timer;
    uint8_t sound_timer;

    // (Чего тут пока нет: экрана и клавиатуры. У CHIP-8 экран 64 на 32 точки и 16 клавиш. Добавим их, когда дойдём до рисования.)

} Chip8; // Закрываем описание структуры и даём этому новому типу данных имя - Chip8.
// Точка с запятой после } обязательна: описание структуры в C считается одной большой командой, а команды заканчиваются ";".


// Функция для загрузки ROM-файла (файла игры) в память эмулятора.
// ROM (Read-Only Memory - память только для чтения) - так исторически называют файл с игрой: раньше игры продавались на микросхемах,
// которые можно было только читать. Внутри .ch8 файла нет ничего, кроме команд процессора CHIP-8, лежащих байт за байтом.
// Ни картинок отдельно, ни звуков - всё в одной куче байтов.
//
// Функция - это кусок кода с именем, который можно вызвать. Как рецепт: написал один раз, а пользоваться можно сколько угодно.
//   Зачем выносить загрузку в отдельную функцию? Чтобы main оставался коротким и понятным,
//   и чтобы потом легко можно было загрузить другую игру одной строчкой.

int load_rom(Chip8 *chip8, const char *filename) {
    // Разбираем первую строчку по кусочкам:
    // int - функция вернёт целое число. У нас договорённость: 1 = всё получилось, 0 = ошибка.
    //   Почему не true/false? В старом C не было отдельного типа "да/нет", поэтому по традиции используют 1 и 0.
    // load_rom - имя функции, придумали сами ("загрузить ром").
    // В скобках - то, что функция получает на вход (параметры):
    //
    // Chip8 *chip8 - звёздочка * означает "указатель". Указатель - это не сама вещь, а её адрес в памяти компьютера.
    //   Представь, что Chip8 - это дом. Если передать в функцию сам дом, Cи сделает его копию, функция загрузит игру в копию,
    //   а настоящий дом останется пустым. Поэтому мы передаём не дом, а его адрес - и функция работает с настоящим домом, а не с его копией.
    //   Вторая причина: наша структура весит больше 4 КБ (одна только память - 4096 байт). Копировать её каждый раз - лишняя работа.
    //   А адрес занимает всего 8 байт, сколько бы ни весил сам дом.
    //   Почему у параметра такое же имя chip8, только с маленькой буквы? Просто удобно. Chip8 (с большой) - это тип, chip8 (с маленькой) - имя переменной.
    //   В C большие и маленькие буквы различаются, для компьютера это два совершенно разных слова.
    //
    // const char *filename - имя файла. char - это один символ (буква), а char * - адрес первой буквы строки, так в C хранится текст.
    //   Как C узнаёт, где строка заканчивается, если у него есть только адрес первой буквы? В конце каждой строки
    //   автоматически стоит невидимый символ с кодом 0 (его пишут '\0'). Функции читают буквы одну за другой, пока не наткнутся на этот ноль.
    //   const значит "константа" - функция обещает не менять это имя, только читать. Если случайно попробуем изменить - компилятор выдаст ошибку.

    // Открываем файл. fopen = file open.
    // "rb" - режим открытия: r = read (только читать), b = binary (бинарный режим).
    // Бинарный режим важен: мы читаем не текст, а сырые байты, и Windows не должна ничего в них "исправлять".
    //   Что именно она исправит? В текстовом режиме Windows превращает пару байтов 0D 0A (перенос строки в Windows) в один байт 0A,
    //   а встретив байт 1A, вообще считает, что файл закончился. Для текста это удобно, а в игре это обычные команды -
    //   если их "поправить", игра превратится в кашу. Поэтому говорим: "отдай байты как есть".
    // FILE *rom - fopen возвращает указатель на специальную структуру FILE, через которую мы дальше будем работать с файлом. Назвали её rom.
    //   Что внутри FILE, нам знать не нужно - это внутренние дела системы. Нам просто дают "ручку" от файла, и мы передаём её в другие функции.
    // Где fopen ищет файл? Если указано только имя без папки - в "текущей рабочей папке", то есть там, откуда запустили программу.
    //   Это частая ловушка: если запускать main.exe из другой папки (например, через кнопку в редакторе), файл может "не найтись", хотя он лежит рядом с main.c.
    FILE *rom = fopen(filename, "rb");

    // Если файл не удалось открыть (его нет, неправильное имя и т.д.), fopen вернёт NULL.
    // NULL - это "пустой указатель", то есть адрес "в никуда" (на деле это просто адрес 0). Значит, файла у нас нет.
    // == - это сравнение ("равно ли?"), не путать с одним = , который присваивает значение.
    //   Если по ошибке написать if (rom = NULL), мы не сравним, а ЗАПИШЕМ NULL в rom - очень коварная и частая ошибка.
    // Зачем проверять? Если продолжить работу с NULL-указателем, программа обратится "в никуда" и просто вылетит без объяснений.
    //   С проверкой мы хотя бы честно напишем человеку, в чём проблема.
    if (rom == NULL) {
        // %s в printf - это место, куда подставится строка (текст), которую мы передали после запятой, - имя файла.
        // \n - перенос на новую строку. Обратная косая черта \ говорит: "следующая буква - не буква, а специальный символ". n = new line.
        printf("Ошибка: Не удалось открыть файл %s\n", filename);
        return 0; // return - выйти из функции и вернуть число. Возвращаем 0 = "не получилось". Всё, что ниже, уже не выполнится.
    }

    // Узнаём размер файла. В C нет готовой команды "дай размер", поэтому делаем хитрость:
    // Представь, что файл - это кассета, а у нас есть головка, которая читает её с какого-то места (её называют "курсор" или "позиция").
    // fseek - перемещает этот курсор. SEEK_END - "от конца файла", 0 - сдвиг на 0 байт от конца. То есть ставим курсор ровно в самый конец.
    fseek(rom, 0 , SEEK_END);
    // ftell - говорит, на каком байте сейчас стоит курсор (считая от начала). Раз мы в самом конце - это и есть размер файла в байтах.
    // long - тоже целое число, как int, но может быть больше. Так решили создатели ftell: она возвращает именно long, вот мы его и берём.
    long rom_size = ftell(rom);
    // rewind - "перемотать". Возвращаем курсор обратно в начало файла, иначе читать будет нечего - мы же в конце, дальше ничего нет.
    rewind(rom);

    // %ld - место для числа типа long (l = long, d = decimal, целое десятичное число).
    // Почему нельзя просто %d? %d рассчитан на int. Если тип не совпадёт, printf может вывести мусор. Каждому типу - свой значок.
    printf("Успешно нашли ROM. Размер: %ld байт.\n", rom_size);

    // Памяти мало, поэтому нужно проверить, влезет ли игра туда.
    // Игра кладётся с адреса 0x200 (512) до конца памяти 0xFFF (4095), значит, свободного места: 4096 - 512 = 3584 байта.
    // Без этой проверки, если файл больше, fread продолжит писать байты дальше конца массива memory,
    //   прямо поверх других переменных или чужой памяти. C тебя от этого НЕ защищает, он не следит за границами массивов.
    //   В лучшем случае программа вылетит, в худшем - будет вести себя странно, и ты долго будешь искать, почему.
    // Скобки вокруг (MEMORY_SIZE - START_ADRESS) - для наглядности: сначала считаем свободное место, потом сравниваем.
    if (rom_size > (MEMORY_SIZE - START_ADRESS)) {
        printf("Ошибка: ROM слишком большой для памяти Chip-8!\n");
        fclose(rom); // Перед выходом обязательно закрываем файл, чтобы не держать его открытым зря.
        return 0;
    }

    // Читаем байты игры прямо в оперативку эмулятора, начиная с адреса 0x200.
    // fread = file read. Разбираем, что ей передаём:
    // &chip8->memory[START_ADRESS] - КУДА положить байты:
    //     chip8->memory - стрелочка -> значит "зайди по указателю chip8 и возьми оттуда memory".
    //       (Если бы у нас была сама структура, а не указатель, писали бы через точку: chip8.memory)
    //       Правило простое: в руках сама вещь - точка, в руках адрес вещи - стрелочка.
    //     [START_ADRESS] - ячейка номер 0x200 (512).
    //     & - знак "адрес". То есть мы говорим: "клади байты, начиная вот с этого места в памяти".
    //       Без & мы бы передали не место, а то, что в этой ячейке лежит (просто число 0), и fread не знала бы, куда писать.
    // sizeof(uint8_t) - размер одного кусочка, который читаем. sizeof говорит, сколько байт занимает тип, у uint8_t это 1 байт.
    // rom_size - сколько таких кусочков прочитать (то есть весь файл).
    //   Почему fread спрашивает отдельно "размер кусочка" и "количество"? Она универсальная: ей можно читать и по 1 байту,
    //   и, например, сразу по целой структуре. В нашем случае: кусочки по 1 байту, rom_size штук.
    // rom - откуда читать (наш открытый файл).
    // Байты из файла лягут в память в том же порядке, в каком лежали в файле: первый байт файла - в ячейку 0x200, второй - в 0x201 и так далее.
    fread(&chip8->memory[START_ADRESS], sizeof(uint8_t), rom_size, rom);

    fclose(rom); // Закрываем файл - он нам больше не нужен, всё уже лежит в памяти эмулятора.
    // Если не закрыть, система держит файл открытым до конца программы. Windows при этом может не дать удалить или изменить
    //   его в другой программе, а количество одновременно открытых файлов ограничено. Правило хорошего тона: открыл - закрой.
    return 1; // Возвращаем 1 = "всё прошло успешно".
}

// main - главная функция. С неё начинается выполнение любой программы на C. Когда ты запускаешь main.exe, компьютер первым делом идёт сюда.
// Имя main придумали не мы - это обязательное правило языка. Если функции main нет, программа даже не соберётся.
// int - main в конце вернёт число операционной системе: 0 означает "программа завершилась нормально".
//   Кому оно нужно? Другим программам и скриптам, которые запустили нашу: по этому числу они понимают, успешно ли всё прошло.
// Пустые скобки () - main ничего не принимает на вход.
int main() {
    // 1. Сразу включаем UTF-8, чтобы консоль Windows понимала русский язык.
    // UTF-8 - это способ записи букв в байтах, который понимает и русский, и английский. Без этого вместо русских букв будут кракозябры.
    // Почему так? Компьютер хранит любую букву как число. Таблица "какое число какой букве соответствует" называется кодировкой.
    //   Наш файл main.c сохранён в UTF-8, а консоль Windows по старой привычке ждёт другую, старую кодировку.
    //   Числа те же, а таблица другая - вот и выходят кракозябры. Эти две строчки говорят консоли: "читай по таблице UTF-8".
    SetConsoleCP(CP_UTF8); // кодировка для ввода (то, что печатаешь в консоль)
    SetConsoleOutputCP(CP_UTF8); // кодировка для вывода (то, что консоль показывает)

    // Создаём экземпляр самой консоли.
    // Chip8 - наш тип из структуры выше, cpu - имя переменной. То есть мы по чертежу "собрали" одну настоящую виртуальную приставку CHIP-8 и назвали её cpu.
    // = {0} - заполнить ВСЁ внутри нулями: память, регистры, стек, таймеры.
    //   Как это работает: в фигурных скобках перечисляют начальные значения полей по порядку. Мы указали только одно - 0.
    //   А по правилам C всё, что не указано, автоматически заполняется нулями. Так одной короткой записью обнуляется вся структура.
    // Это важно: в C новая переменная не чистая, в ней может лежать случайный мусор, оставшийся в памяти компьютера от других программ.
    //   Настоящая приставка при включении тоже начинает с чистого листа, поэтому и мы начинаем с нулей.
    Chip8 cpu = {0};

    // Настраиваем стартовое состояние процессора.
    // Точка . - так мы обращаемся к переменной внутри структуры: cpu.pc = "pc, который лежит внутри cpu".
    //   Здесь точка, а не стрелочка, потому что cpu - это сама приставка, а не её адрес.
    cpu.pc = START_ADRESS; // Процессор начнёт читать команды с адреса 0x200 - именно там будет лежать начало игры.
    // Если забыть эту строчку, pc останется равным 0, и процессор начнёт читать "команды" из пустой области,
    //   где никакой игры нет. Игра просто не запустится.

    printf("Эмулятор Chip-8 инициализирован\n"); // инициализирован = подготовлен к работе, всё выставлено в начальное состояние.

    // Имя файла игры. Скачай любой .ch8 файл (например, Pong.ch8 или IBM Logo.ch8)
    // и положи его в папку roms/ в корне проекта. Путь "roms/..." считается от папки, откуда запускаешь main.exe.
    // Двойные кавычки " " - так в C записывается текст (строка). Одинарные ' ' - только для ОДНОГО символа, например 'A'.
    // Почему const char *? Текст "roms/Pong.ch8" компилятор вшивает прямо в программу, и менять его нельзя. const честно это показывает.
    const char *rom_path = "roms/Pong.ch8";

    // Вызываем нашу функцию загрузки.
    // &cpu - знак & берёт АДРЕС нашей приставки cpu. Помнишь, функция ждёт указатель (Chip8 *chip8)? Вот мы его и даём.
    //   * и & - пара противоположностей: & - "дай адрес этой вещи", * - "это адрес вещи такого-то типа".
    // if (...) - если функция вернула 1 (успех), выполняем то, что в фигурных скобках. Если 0 - пропускаем.
    // В C любое число, кроме 0, считается "правдой", а 0 - "ложью". Поэтому можно не писать == 1, хватает просто вызова функции.
    // Обрати внимание: функция и выполняется (загружает игру), и одновременно её ответ сразу проверяется. Всё в одной строчке.
    if (load_rom(&cpu, rom_path)) {
        printf("ROM успешно загружен в виртуальную память\n");

        // Попробуем вывести хоть что-то - выведем первые несколько байт загруженной игры, чтобы убедиться, что всё загрузилось.
        // Цикл for - повторяет код внутри много раз. Разбираем его скобки (три части через точку с запятой):
        //   int i = 0 - заводим счётчик i и начинаем с нуля. (Почему с нуля? Нумерация в C с нуля: первый байт игры - это START_ADRESS + 0.)
        //   i < 10    - крутим цикл, пока i меньше 10. Как только станет 10 - выходим.
        //   i += 2    - после каждого круга прибавляем к i двойку (i = i + 2). Получится i = 0, 2, 4, 6, 8 - то есть 5 кругов.
        // Почему шагаем по 2? Потому что каждая команда CHIP-8 занимает ровно 2 байта. За один круг цикла читаем одну команду.
        // Счётчик i существует только внутри цикла. После закрывающей } его уже нет - так меньше путаницы с именами.
        for (int i = 0; i < 10; i += 2) {
            uint8_t byte1 = cpu.memory[START_ADRESS + i]; // первый байт команды (старшая половина)
            uint8_t byte2 = cpu.memory[START_ADRESS + i + 1]; // второй байт команды (младшая половина), он лежит сразу за первым
            // Что значит "старшая" и "младшая"? Как в числе 47: 4 - старшая цифра (десятки), 7 - младшая (единицы).
            //   CHIP-8 хранит команды "старшим байтом вперёд", то есть в памяти они лежат в том же порядке, в каком мы их читаем.
            //   Поэтому печатаем byte1, а потом byte2 - и получаем команду ровно такой, какой её записали в документации.

            // %03X - выведет адрес в шестнадцатеричном виде (X = шестнадцатеричное число большими буквами, 3 = минимум 3 символа, 0 = недостающие места заполнить нулями)
            // %02X%02X - выведет два байта команды склеенными вместе, каждый ровно 2 символа. Например, байты 6A и 02 покажутся как 6A02.
            //   Зачем 02 (дополнять нулём)? Байт 2 без этого напечатался бы как "2", и вместо 6A02 мы увидели бы 6A2 - непонятно, где какой байт.
            // Значения подставляются по порядку: первый % получает START_ADRESS + i, второй - byte1, третий - byte2.
            //
            // Что значат эти загадочные 6A02, A2EA? Это и есть команды игры! Первая цифра обычно говорит, что это за команда:
            //   6A02 = "6" (положить число в регистр), "A" (регистр VA), "02" (число 2) -> "положи 2 в регистр VA".
            //   A2EA = "A" (записать адрес в I), "2EA" (адрес) -> "I = 0x2EA", то есть "запомни, где лежит картинка".
            //   Научить эмулятор понимать и выполнять такие команды - это и есть наш следующий большой шаг.
            printf("Адрес 0x%03X: %02X%02X\n", START_ADRESS + i, byte1, byte2);
        }
    }

    return 0; // Программа закончилась нормально - возвращаем 0 операционной системе.
}
